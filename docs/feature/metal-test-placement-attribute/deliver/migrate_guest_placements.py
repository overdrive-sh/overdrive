#!/usr/bin/env python3
"""Moves guest-group placements from infra/metal/test-placement.json onto the
tests they place (temporary migration tool; deleted at retirement).

For each selected table entry the script finds the test function by binary id
and module path, adds `#[overdrive_test(guest = "<group>")]`
directly above the function (and `use overdrive_testing::overdrive_test;` to the
file when it lacks that import), adds `overdrive-testing` to the owning crate's
dev-dependencies when the crate lacks it, and deletes the table entry.

It reads the table by parsing the JSON. It never adds a table entry, never
changes a group (the group written on the test is the group the entry carried),
and reports, without touching, any entry it cannot place unambiguously: a
missing function, two functions of one name, a function inside a macro, a
binary outside the workspace. Reported entries stay in the table.

A binary id with no `::<target>` suffix is the package's lib test binary
(`src/lib.rs`); its unit tests sit in inline `mod` blocks, so the import goes in
the innermost enclosing inline module (the dev-dependency is not a normal one).
A test generated by a `macro_rules!` template (`$name:ident`) takes ONE
attribute inside the template, when every test the template generates is
selected with the same group and profile.

`--profiles FILE` names a JSON object of "<binary>::<test>" -> profile: the
profile written on that test as `profile = "<profile>"`. A test with no entry
selects the group's base profile (omitted).

Usage: migrate_guest_placements.py --groups core,probe,... [--acknowledge FILE]
       [--profiles FILE] [--dry-run]

`--acknowledge` names a JSON object of "<binary>::<test>" -> reason: entries
held back on purpose (reported to the user, left in the table, never migrated).
Any other report makes the exit status 3 and nothing changes.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
TABLE = ROOT / "infra/metal/test-placement.json"
ATTRIBUTE = '#[overdrive_test(guest = "{group}")]'
ATTRIBUTE_WITH_PROFILE = '#[overdrive_test(guest = "{group}", profile = "{profile}")]'
IMPORT = "use overdrive_testing::overdrive_test;"
IMPORT_PATTERN = re.compile(
    r"^\s*use overdrive_testing::(\{[^}]*\boverdrive_test\b[^}]*\}|overdrive_test);", re.M
)
TOP_IMPORT_PATTERN = re.compile(
    r"^use overdrive_testing::(\{[^}]*\boverdrive_test\b[^}]*\}|overdrive_test);", re.M
)


def inner_end(lines, start):
    """Index after the last inner doc/attribute line of the leading region of
    `lines[start:]` (blank lines, `//` comments, `//!` docs and possibly
    multi-line `#![...]` attributes); `start` when there is none."""
    end = start
    index = start
    while index < len(lines):
        line = lines[index].strip()
        if line.startswith("#![") or line.startswith("#["):
            balance = line.count("[") - line.count("]")
            last = index
            while balance > 0:
                last += 1
                balance += lines[last].count("[") - lines[last].count("]")
            if line.startswith("#!["):
                end = last + 1
            else:
                break
            index = last + 1
        elif line.startswith("//!"):
            end = index + 1
            index += 1
        elif line == "" or line.startswith("//"):
            index += 1
        else:
            break
    return end


def with_import(text):
    """`text` with the `overdrive_test` import added after the last
    non-std/crate-local top-level `use`, unless the file already imports it."""
    if TOP_IMPORT_PATTERN.search(text):
        return text
    lines = text.split("\n")
    last = None
    last_any = None
    index = 0
    while index < len(lines):
        if re.match(r"use ", lines[index]):
            end = index
            while not lines[end].rstrip().endswith(";"):
                end += 1
            last_any = end
            if not re.match(r"use (super|crate|self|std|core)\b", lines[index]):
                last = end
            index = end + 1
        else:
            index += 1
    at = last if last is not None else last_any
    if at is None:
        header = inner_end(lines, 0)
        lines[header:header] = ["", IMPORT] if header else [IMPORT, ""]
        return "\n".join(lines)
    lines.insert(at + 1, IMPORT)
    return "\n".join(lines)


def workspace_members():
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--no-deps", "--format-version", "1", "--offline"],
            cwd=ROOT,
        )
    )
    return {p["name"]: Path(p["manifest_path"]).parent for p in meta["packages"]}


def module_file(root_file, segments):
    """The file and the remaining inline-module depth holding `segments`."""
    file = root_file
    base = root_file.parent
    text = file.read_text()
    for segment in segments:
        if re.search(rf"^\s*(pub(\([a-z]+\))?\s+)?mod\s+{re.escape(segment)}\s*\{{", text, re.M):
            base = base / segment
            continue
        candidate = base / f"{segment}.rs"
        if candidate.is_file():
            file = candidate
            text = file.read_text()
            base = base / segment
            continue
        candidate = base / segment / "mod.rs"
        if candidate.is_file():
            file = candidate
            text = file.read_text()
            base = base / segment
            continue
        return None
    return file


def inside_macro(lines, index):
    """True when line `index` is inside a macro_rules! body."""
    depth = 0
    in_macro = False
    macro_depth = 0
    for number, line in enumerate(lines):
        stripped = line.split("//")[0]
        if re.search(r"\bmacro_rules!", stripped) and not in_macro:
            in_macro = True
            macro_depth = depth
        if number == index and in_macro:
            return True
        depth += stripped.count("{") - stripped.count("}")
        if in_macro and depth <= macro_depth and "}" in stripped and number > 0:
            if depth <= macro_depth:
                in_macro = False
    return False


def locate(members, binary, test):
    """(file, line index of `fn`) or a string describing why not."""
    package, _, target = binary.partition("::")
    if package not in members:
        return f"binary {binary} is not a workspace package"
    directory = members[package]
    root_file = directory / ("src/lib.rs" if not target else f"tests/{target}.rs")
    if not root_file.is_file():
        return f"no test target file {root_file.relative_to(ROOT)}"
    *modules, leaf = test.split("::")
    file = module_file(root_file, modules)
    if file is None:
        return f"module path {'::'.join(modules)} does not resolve from {root_file.relative_to(ROOT)}"
    lines = file.read_text().split("\n")
    pattern = re.compile(rf"\bfn\s+{re.escape(leaf)}\s*[(<]")
    hits = [i for i, line in enumerate(lines) if pattern.search(line)]
    if not hits:
        return ("template", file, leaf)
    if len(hits) > 1:
        return f"{len(hits)} fns named {leaf} in {file.relative_to(ROOT)}"
    index = hits[0]
    if inside_macro(lines, index):
        return f"fn {leaf} is inside a macro_rules! body in {file.relative_to(ROOT)}"
    above = index - 1
    attributes = []
    test_at = None
    while above >= 0 and (
        lines[above].lstrip().startswith("#[") or lines[above].lstrip().startswith(")")
        or lines[above].lstrip().startswith("//")
    ):
        attributes.append(lines[above])
        if re.match(r"\s*#\[(tokio::)?test\b", lines[above]):
            test_at = above
        above -= 1
    if test_at is None:
        return f"fn {leaf} in {file.relative_to(ROOT)} carries no #[test]"
    if any("overdrive_test" in line for line in attributes):
        return f"fn {leaf} in {file.relative_to(ROOT)} already carries a placement"
    return file, test_at, index


def ensure_dev_dependency(directory):
    manifest = directory / "Cargo.toml"
    text = manifest.read_text()
    section = re.search(r"^\[dev-dependencies\]\n(.*?)(?=^\[|\Z)", text, re.M | re.S)
    dependencies = re.search(r"^\[dependencies\]\n(.*?)(?=^\[|\Z)", text, re.M | re.S)
    for found in (section, dependencies):
        if found and re.search(r"^overdrive-testing\b", found.group(1), re.M):
            return False
    line = "# `#[overdrive_test]` places the guest-placed tests.\noverdrive-testing.workspace = true\n"
    if section:
        end = section.end(1)
        body = section.group(1)
        text = text[:end] + ("" if body.endswith("\n") else "\n") + line + text[end:]
    else:
        text = text.rstrip("\n") + "\n\n[dev-dependencies]\n" + line
    manifest.write_text(text)
    return True


def template_site(file, leaf):
    """For a test generated by a `macro_rules!` template: (test attribute line
    index inside the template, the template's start line, the idents the
    invocation lists), or a string describing why not."""
    lines = file.read_text().split("\n")
    call = next((i for i, l in enumerate(lines) if re.match(rf"\s*{re.escape(leaf)}\s*=>", l)), None)
    if call is None:
        return f"no fn {leaf} and no template invocation naming it in {file.relative_to(ROOT)}"
    start = call
    while start >= 0 and not re.match(r"\w+!\s*\{", lines[start]):
        start -= 1
    if start < 0:
        return f"template invocation of {leaf} in {file.relative_to(ROOT)} has no `name! {{` opener"
    name = re.match(r"(\w+)!", lines[start]).group(1)
    idents = []
    end = start + 1
    while end < len(lines) and not lines[end].startswith("}"):
        found = re.match(r"\s*(\w+)\s*=>", lines[end])
        if found:
            idents.append(found.group(1))
        end += 1
    definition = next(
        (i for i, l in enumerate(lines) if re.match(rf"macro_rules!\s+{name}\b", l)), None
    )
    if definition is None:
        return f"template {name} is not defined in {file.relative_to(ROOT)}"
    body_end = definition + 1
    while body_end < len(lines) and not lines[body_end].startswith("}"):
        body_end += 1
    body = range(definition, body_end)
    test_at = next(
        (i for i in body if re.match(r"\s*#\[(tokio::)?test\b", lines[i])), None
    )
    if test_at is None:
        return f"template {name} in {file.relative_to(ROOT)} carries no #[test]"
    if not re.search(r"fn\s+\$\w+", "\n".join(lines[test_at : body_end])):
        return f"template {name} in {file.relative_to(ROOT)} does not name its fn from a $ident"
    if any("overdrive_test" in lines[i] for i in body):
        return f"template {name} in {file.relative_to(ROOT)} already carries a placement"
    return test_at, definition, idents


def enclosing_inline_module(lines, index):
    """Line index of the innermost inline `mod x {` enclosing line `index`."""
    indent = len(re.match(r"\s*", lines[index]).group(0))
    for above in range(index - 1, -1, -1):
        found = re.match(r"(\s*)(pub(\([a-z]+\))?\s+)?mod\s+\w+\s*\{\s*$", lines[above])
        if found and len(found.group(1)) < indent:
            return above
    return None


def import_line_in_module(lines, module):
    """Line index after which the import goes inside inline module `module`
    (None when the module already imports it): after its last `use`, else
    after its inner docs and attributes."""
    last = inner_end(lines, module + 1) - 1
    last = max(last, module)
    index = module + 1
    while index < len(lines):
        line = lines[index].strip()
        if line.startswith("use "):
            if IMPORT_PATTERN.match(lines[index]):
                return None
            end = index
            while not lines[end].rstrip().endswith(";"):
                end += 1
            last = max(last, end)
            index = end + 1
        elif line.startswith("#"):
            balance = line.count("[") - line.count("]")
            while balance > 0:
                index += 1
                balance += lines[index].count("[") - lines[index].count("]")
            index += 1
        elif line == "" or line.startswith("//"):
            index += 1
        else:
            break
    return last


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--groups", required=True)
    parser.add_argument("--acknowledge")
    parser.add_argument("--profiles")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    groups = set(args.groups.split(","))
    acknowledged = json.loads(Path(args.acknowledge).read_text()) if args.acknowledge else {}
    profiles = json.loads(Path(args.profiles).read_text()) if args.profiles else {}

    original = TABLE.read_text()
    table = json.loads(original)
    assert json.dumps(table, indent=2, ensure_ascii=False) + "\n" == original, "table is not canonical"
    members = workspace_members()

    selected = [
        (binary, test, descriptor)
        for binary, tests in table["placements"].items()
        for test, descriptor in tests.items()
        if descriptor["kind"] == "guest-group" and descriptor["group"] in groups
    ]
    findings = []
    plan = []
    for binary, test, descriptor in selected:
        if f"{binary}::{test}" in acknowledged:
            findings.append((binary, test, "held: " + acknowledged[f"{binary}::{test}"]))
            continue
        if set(descriptor) != {"kind", "group"}:
            findings.append((binary, test, f"descriptor has unexpected fields {sorted(descriptor)}"))
            continue
        where = locate(members, binary, test)
        if isinstance(where, str):
            findings.append((binary, test, where))
            continue
        profile = profiles.get(f"{binary}::{test}", "")
        attribute = (
            ATTRIBUTE_WITH_PROFILE.format(group=descriptor["group"], profile=profile)
            if profile
            else ATTRIBUTE.format(group=descriptor["group"])
        )
        if where[0] == "template":
            _, file, leaf = where
            site = template_site(file, leaf)
            if isinstance(site, str):
                findings.append((binary, test, site))
                continue
            test_at, definition, idents = site
            plan.append((binary, test, descriptor["group"], profile, attribute, file, test_at, (file, definition, tuple(idents)), leaf))
        else:
            file, test_at, _index = where
            plan.append((binary, test, descriptor["group"], profile, attribute, file, test_at, None, test.split("::")[-1]))

    # A template takes one attribute: every ident it generates must be selected
    # here with one and the same attribute.
    by_template = {}
    for binary, test, group, profile, attribute, file, test_at, key, leaf in plan:
        if key is not None:
            by_template.setdefault(key, []).append((binary, test, attribute, leaf))
    for key, members_of in by_template.items():
        _, definition, idents = key
        attributes = {m[2] for m in members_of}
        generated = {m[3] for m in members_of}
        if len(attributes) != 1 or generated != set(idents):
            for binary, test, _, _ in members_of:
                findings.append((binary, test, f"template at line {definition + 1} generates {sorted(idents)}, selected {sorted(generated)} with attributes {sorted(attributes)}"))
    templated_bad = {(b, t) for b, t, *_ in [(f[0], f[1]) for f in findings]}
    plan = [p for p in plan if (p[0], p[1]) not in templated_bad]

    unacknowledged = [f for f in findings if f"{f[0]}::{f[1]}" not in acknowledged]
    for binary, test, reason in findings:
        mark = "acknowledged" if f"{binary}::{test}" in acknowledged else "STOP"
        print(f"{mark}: {binary}::{test}: {reason}", file=sys.stderr)
    if unacknowledged:
        print(f"{len(unacknowledged)} unacknowledged finding(s); nothing changed", file=sys.stderr)
        return 3

    edits = {}
    seen_templates = set()
    for binary, test, group, profile, attribute, file, test_at, key, leaf in plan:
        if key is not None:
            if key in seen_templates:
                continue
            seen_templates.add(key)
        edits.setdefault((file, False), {})[test_at] = attribute
    for (file, _), at in edits.items():
        lines = file.read_text().split("\n")
        ordered = sorted(at.items())
        final = []
        for count, (index, attribute) in enumerate(ordered):
            final.append(index + count)
        for index, attribute in sorted(ordered, reverse=True):
            indent = re.match(r"\s*", lines[index]).group(0)
            lines.insert(index, indent + attribute)
        points = set()
        top_level = False
        for position in final:
            module = enclosing_inline_module(lines, position)
            if module is None:
                top_level = True
            else:
                points.add(module)
        insertions = {}
        for module in points:
            after = import_line_in_module(lines, module)
            if after is not None:
                indent = re.match(r"\s*", lines[module]).group(0) + "    "
                insertions[after] = indent + IMPORT
        for after, line in sorted(insertions.items(), reverse=True):
            lines.insert(after + 1, line)
        text = "\n".join(lines)
        if top_level:
            text = with_import(text)
        if not args.dry_run:
            file.write_text(text)
    if not args.dry_run:
        for file, _ in edits:
            owner = next(
                directory for directory in members.values() if directory in file.parents
            )
            if ensure_dev_dependency(owner):
                print(f"added overdrive-testing to {owner.relative_to(ROOT)}/Cargo.toml")
        for binary, test, *_ in plan:
            del table["placements"][binary][test]
            if not table["placements"][binary]:
                del table["placements"][binary]
        TABLE.write_text(json.dumps(table, indent=2, ensure_ascii=False) + "\n")
    per_group = {}
    for _, _, group, *_ in plan:
        per_group[group] = per_group.get(group, 0) + 1
    print(json.dumps({"migrated": per_group, "left": len(findings)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
