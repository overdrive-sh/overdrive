//! The two host adapters of the forwarder's upstream ports on real I/O (GH #382;
//! ADR-0356, ADR-0358): `ResolvConfUpstreams` against real files and
//! `HostUpstreamExchange` against real UDP and TCP sockets.
//!
//! Driving ports: `UpstreamResolvers::candidates` and `UpstreamExchange::exchange`
//! (the only surface the forwarder uses). Oracles: the returned candidates or
//! error variant, the reply bytes, and what the raw upstream socket received.
//! Layer 3: example-only, one named test per failure mode (Mandate 11).
//!
//! The file tests touch only a temporary directory (host-pure); the exchange
//! tests bind `127.0.0.2:53`, so each runs in its own guest.

#![allow(
    clippy::expect_used,
    clippy::unwrap_used,
    clippy::too_many_lines,
    clippy::doc_markdown,
    reason = "Tier-3 acceptance body; failures panic with informative messages"
)]

use std::io::{self, Read, Write};
use std::net::{IpAddr, Ipv4Addr, Ipv6Addr, SocketAddrV4, TcpListener, UdpSocket};
use std::time::{Duration, Instant};

use hickory_proto::op::Message;
use overdrive_control_plane::dns_responder::upstream::{
    DnsTransport, ExchangeError, UpstreamConfigError, UpstreamExchange, UpstreamResolvers,
};
use overdrive_control_plane::dns_responder::upstream_host::{
    HostUpstreamExchange, ResolvConfUpstreams,
};
use overdrive_testing::overdrive_test;
use tempfile::TempDir;

const SERVER: Ipv4Addr = Ipv4Addr::new(127, 0, 0, 2);

// ---------------------------------------------------------------------------
// ResolvConfUpstreams (ADR-0358): the host resolver file, read on every call
// ---------------------------------------------------------------------------

fn file_with(body: &str) -> (TempDir, ResolvConfUpstreams) {
    let dir = TempDir::new().expect("tempdir");
    let path = dir.path().join("resolv.conf");
    std::fs::write(&path, body).expect("write resolver file");
    (dir, ResolvConfUpstreams::from_path(path))
}

#[overdrive_test(host_pure)]
#[tokio::test]
async fn nameserver_lines_are_listed_in_file_order_and_everything_else_is_ignored() {
    let (_dir, upstreams) = file_with(
        "# generated by dhcpcd\nsearch corp.example\noptions edns0 trust-ad\n\
         nameserver 192.168.1.1\nnameserver fe80::1%eth0\nnameserver 2001:4860:4860::8888\n\
         nameserver not-an-address\nnameserver 10.0.0.53\n",
    );
    let candidates = upstreams.candidates().await.expect("a readable file lists its nameservers");
    assert_eq!(
        candidates,
        vec![
            IpAddr::V4(Ipv4Addr::new(192, 168, 1, 1)),
            IpAddr::V6("2001:4860:4860::8888".parse::<Ipv6Addr>().unwrap()),
            IpAddr::V4(Ipv4Addr::new(10, 0, 0, 53)),
        ],
        "file order preserved, a scoped or malformed token skipped, other lines ignored"
    );
}

#[overdrive_test(host_pure)]
#[tokio::test]
async fn a_readable_file_with_no_nameserver_line_is_an_empty_list_not_an_error() {
    let (_dir, upstreams) = file_with("# nothing configured yet\nsearch corp.example\n");
    assert!(upstreams.candidates().await.expect("readable").is_empty());
}

#[overdrive_test(host_pure)]
#[tokio::test]
async fn a_missing_file_is_absent_and_an_unreadable_one_is_a_distinct_error() {
    let dir = TempDir::new().expect("tempdir");
    let missing = ResolvConfUpstreams::from_path(dir.path().join("no-such-file"));
    assert!(matches!(missing.candidates().await, Err(UpstreamConfigError::Absent)));
    // A directory in the file's place reads as an I/O error that is not NotFound.
    let unreadable = ResolvConfUpstreams::from_path(dir.path());
    assert!(matches!(unreadable.candidates().await, Err(UpstreamConfigError::Unreadable { .. })));
}

#[overdrive_test(host_pure)]
#[tokio::test]
async fn the_file_is_re_read_on_every_call_so_a_replaced_file_takes_effect_at_once() {
    let (dir, upstreams) = file_with("nameserver 192.168.1.1\n");
    let path = dir.path().join("resolv.conf");
    assert_eq!(
        upstreams.candidates().await.unwrap(),
        vec![IpAddr::V4(Ipv4Addr::new(192, 168, 1, 1))]
    );
    std::fs::write(&path, "nameserver 10.0.0.53\n").expect("replace");
    assert_eq!(
        upstreams.candidates().await.unwrap(),
        vec![IpAddr::V4(Ipv4Addr::new(10, 0, 0, 53))]
    );
    std::fs::remove_file(&path).expect("remove");
    assert!(matches!(upstreams.candidates().await, Err(UpstreamConfigError::Absent)));
}

// ---------------------------------------------------------------------------
// HostUpstreamExchange (ADR-0356): one fresh socket per exchange, verified reply
// ---------------------------------------------------------------------------

fn wire_query(id: u16, name: &str) -> Vec<u8> {
    use hickory_proto::op::{MessageType, OpCode, Query};
    use hickory_proto::rr::{Name, RecordType};
    let mut m = Message::new(id, MessageType::Query, OpCode::Query);
    m.metadata.recursion_desired = true;
    m.add_query(Query::query(Name::from_ascii(name).expect("name"), RecordType::A));
    m.to_vec().expect("encode")
}

/// A response to `query`: the same question, optionally a different id or name.
fn response_to(query: &[u8], id: Option<u16>, name: Option<&str>) -> Vec<u8> {
    use hickory_proto::op::{MessageType, OpCode, Query};
    use hickory_proto::rr::{Name, RecordType};
    let q = Message::from_vec(query).expect("query");
    let mut m = Message::new(id.unwrap_or(q.metadata.id), MessageType::Response, OpCode::Query);
    let question = name.map_or_else(
        || q.queries[0].clone(),
        |n| Query::query(Name::from_ascii(n).expect("name"), RecordType::A),
    );
    m.add_query(question);
    m.to_vec().expect("encode")
}

fn udp_server() -> UdpSocket {
    let socket = UdpSocket::bind(SocketAddrV4::new(SERVER, 53)).expect("bind the raw upstream");
    socket.set_read_timeout(Some(Duration::from_secs(5))).expect("timeout");
    socket
}

#[overdrive_test(guest = "cgroup-default", profile = "normal-gate")]
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_udp_exchange_returns_the_matching_reply_and_ignores_a_wrong_id_and_a_wrong_question() {
    let server = udp_server();
    let q = wire_query(0x1111, "github.com.");
    let q2 = q.clone();
    let thread = std::thread::spawn(move || {
        let mut buf = [0u8; 1500];
        let (n, peer) = server.recv_from(&mut buf).expect("the upstream receives the query");
        assert_eq!(&buf[..n], &q2[..], "the query is sent unchanged");
        // Hostile first: a wrong id and a wrong question, then the real reply.
        server.send_to(&response_to(&q2, Some(0x2222), None), peer).unwrap();
        server.send_to(&response_to(&q2, None, Some("evil.example.")), peer).unwrap();
        let good = response_to(&q2, None, None);
        server.send_to(&good, peer).unwrap();
        good
    });
    let reply = HostUpstreamExchange
        .exchange(IpAddr::V4(SERVER), DnsTransport::Udp, &q, Duration::from_secs(3))
        .await
        .expect("the matching reply is returned");
    assert_eq!(reply, thread.join().unwrap(), "only the matching reply is returned");
}

#[overdrive_test(guest = "cgroup-default", profile = "normal-gate")]
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_silent_upstream_is_a_timeout_and_a_closed_port_is_unreachable_not_a_timeout() {
    let q = wire_query(7, "crates.io.");
    let exchange = HostUpstreamExchange;
    // Nothing listens on 127.0.0.2:53 yet: the kernel answers with an ICMP error.
    let started = Instant::now();
    let refused =
        exchange.exchange(IpAddr::V4(SERVER), DnsTransport::Udp, &q, Duration::from_secs(3)).await;
    assert!(matches!(refused, Err(ExchangeError::Unreachable { .. })), "{refused:?}");
    assert!(started.elapsed() < Duration::from_millis(500), "a refusal is not a wait");

    let _silent = udp_server();
    let started = Instant::now();
    let silent = exchange
        .exchange(IpAddr::V4(SERVER), DnsTransport::Udp, &q, Duration::from_millis(400))
        .await;
    assert!(matches!(silent, Err(ExchangeError::Timeout)), "{silent:?}");
    let waited = started.elapsed();
    assert!(
        waited >= Duration::from_millis(400) && waited < Duration::from_millis(900),
        "{waited:?}"
    );
}

#[overdrive_test(guest = "cgroup-default", profile = "normal-gate")]
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_udp_reply_that_fills_the_receive_buffer_is_reply_too_large() {
    let server = udp_server();
    let q = wire_query(9, "big.example.");
    let thread = std::thread::spawn(move || {
        let mut buf = [0u8; 1500];
        let (_, peer) = server.recv_from(&mut buf).expect("query");
        // MAX_GUEST_DATAGRAM_PAYLOAD + 1 = 59 001 bytes fills the buffer.
        server.send_to(&vec![0u8; 59_001], peer).expect("send an oversize datagram");
    });
    let result = HostUpstreamExchange
        .exchange(IpAddr::V4(SERVER), DnsTransport::Udp, &q, Duration::from_secs(3))
        .await;
    thread.join().unwrap();
    assert!(matches!(result, Err(ExchangeError::ReplyTooLarge)), "{result:?}");
}

#[overdrive_test(guest = "cgroup-default", profile = "normal-gate")]
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_tcp_exchange_frames_one_query_per_connection_and_rejects_a_mismatched_reply() {
    let listener = TcpListener::bind(SocketAddrV4::new(SERVER, 53)).expect("bind TCP upstream");
    let q = wire_query(0x3333, "github.com.");
    let q2 = q.clone();
    let thread = std::thread::spawn(move || {
        let serve_one = |reply: &dyn Fn(&[u8]) -> Vec<u8>| {
            let (mut s, _) = listener.accept().expect("accept");
            let mut len = [0u8; 2];
            s.read_exact(&mut len).expect("length prefix");
            let mut body = vec![0u8; usize::from(u16::from_be_bytes(len))];
            s.read_exact(&mut body).expect("body");
            assert_eq!(body, q2, "the query is sent unchanged, length-prefixed");
            let out = reply(&body);
            s.write_all(&u16::try_from(out.len()).unwrap().to_be_bytes()).unwrap();
            s.write_all(&out).unwrap();
            out
        };
        serve_one(&|b| response_to(b, None, None))
    });
    let exchange = HostUpstreamExchange;
    let reply = exchange
        .exchange(IpAddr::V4(SERVER), DnsTransport::Tcp, &q, Duration::from_secs(3))
        .await
        .expect("a TCP reply that matches");
    assert_eq!(reply, thread.join().unwrap());

    // A second connection answered with the wrong id fails the attempt as InvalidData.
    let listener = TcpListener::bind(SocketAddrV4::new(SERVER, 53)).expect("rebind");
    let q3 = q.clone();
    let wrong = std::thread::spawn(move || {
        let (mut s, _) = listener.accept().expect("accept");
        let mut len = [0u8; 2];
        s.read_exact(&mut len).unwrap();
        let mut body = vec![0u8; usize::from(u16::from_be_bytes(len))];
        s.read_exact(&mut body).unwrap();
        let out = response_to(&q3, Some(0x9999), None);
        s.write_all(&u16::try_from(out.len()).unwrap().to_be_bytes()).unwrap();
        s.write_all(&out).unwrap();
    });
    let result =
        exchange.exchange(IpAddr::V4(SERVER), DnsTransport::Tcp, &q, Duration::from_secs(3)).await;
    wrong.join().unwrap();
    match result {
        Err(ExchangeError::Io { source }) => assert_eq!(source.kind(), io::ErrorKind::InvalidData),
        other => panic!("a mismatched TCP reply is Io(InvalidData): {other:?}"),
    }
}
